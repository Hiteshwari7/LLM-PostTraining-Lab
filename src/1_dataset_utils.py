"""
dataset_utils.py

Shared helpers for loading and formatting the datasets used across the
post-training pipeline.

WHAT this module does:
- Reads raw .txt, .jsonl, and .json files.
- Creates token chunks for Stage 1 continued pretraining.
- Formats instruction data for Stage 2 SFT.
- Formats preference data for Stage 3 DPO.
- Loads and normalizes evaluation questions.

WHY a separate module:
Keeping data-processing logic outside the notebooks makes it reusable
by the training scripts and easier to maintain.
"""

import json
from datasets import Dataset


SYSTEM_PROMPT = (
    "You are PostTraining Tutor, an assistant that explains LLM training "
    "concepts (Transformers, LoRA, QLoRA, SFT, DPO, RLHF, alignment) "
    "clearly and concisely."
)


def load_jsonl(path):
    """
    WHAT: Read a .jsonl file into a list of dictionaries.

    WHY: instruction_dataset.jsonl and preference_dataset.jsonl
    use the JSON Lines format.
    """
    rows = []

    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()

            if line:
                rows.append(json.loads(line))

    return rows


def load_json(path):
    """
    WHAT: Read a regular JSON file.

    Used for evaluation_questions.json.
    """
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def chunk_corpus(tokenizer, corpus_path, max_seq_length):
    """
    WHAT: Split the raw text corpus into token chunks of at most
    max_seq_length tokens.

    WHY: Continued pretraining needs manageable training examples
    rather than one extremely long text sequence.
    """

    with open(corpus_path, "r", encoding="utf-8") as f:
        raw_text = f.read()

    tokens = tokenizer(
        raw_text,
        return_tensors=None
    )["input_ids"]

    chunks = [
        tokens[i:i + max_seq_length]
        for i in range(0, len(tokens), max_seq_length)
        if len(tokens[i:i + max_seq_length]) > 20
    ]

    # Convert token chunks back into text because SFTTrainer
    # receives the dataset through the "text" column.
    texts = [tokenizer.decode(chunk) for chunk in chunks]

    return Dataset.from_dict({"text": texts})


def build_sft_dataset(tokenizer, instruction_path):
    """
    WHAT: Load instruction/input/output examples and render them
    using the model's chat template.

    WHY: The model should see the same system/user/assistant structure
    during training that it will see during inference.
    """

    rows = load_jsonl(instruction_path)

    def format_example(example):

        # Combine instruction and optional input.
        user_content = example["instruction"]

        if example.get("input"):
            user_content += "\n\n" + example["input"]

        messages = [
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": user_content,
            },
            {
                "role": "assistant",
                "content": example["output"],
            },
        ]

        text = tokenizer.apply_chat_template(
            messages,
            tokenize=False,
            add_generation_prompt=False,
        )

        return {"text": text}

    return Dataset.from_list(rows).map(format_example)


def build_dpo_dataset(tokenizer, preference_path):
    """
    WHAT: Load preference examples containing prompt, chosen, and rejected.

    WHY: DPO needs two responses to the same prompt:
    one preferred response and one rejected response.
    """

    rows = load_jsonl(preference_path)

    def format_prompt(example):

        messages = [
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": example["prompt"],
            },
        ]

        prompt_text = tokenizer.apply_chat_template(
            messages,
            tokenize=False,
            add_generation_prompt=True,
        )

        return {
            "prompt": prompt_text,
            "chosen": example["chosen"],
            "rejected": example["rejected"],
        }

    return Dataset.from_list(rows).map(format_prompt)


def load_evaluation_questions(eval_path):
    """
    WHAT: Normalize evaluation_questions.json into a flat list of
    question strings.

    Supports either:

        ["question 1", "question 2"]

    or:

        [{"question": "question 1"}, {"question": "question 2"}]
    """

    data = load_json(eval_path)

    if data and isinstance(data[0], dict):
        return [item["question"] for item in data]

    return data